function SidebarMenuButton({
  render,
  isActive = false,
  variant = "default",
  size = "default",
  tooltip,
  className,
  ...props
}: useRender.ComponentProps<"button"> &
  ComponentProps<"button"> & {
    isActive?: boolean;
    tooltip?:
      | string
      | (ComponentProps<typeof TooltipContent> & { delay?: number });
  } & VariantProps<typeof sidebarMenuButtonVariants>) {
  const { isMobile, state } = useSidebar();

  const menuButtonClassName = cn(
    sidebarMenuButtonVariants({ variant, size }),
    isActive && "selected",
    className
  );

  let tooltipOpenDelay: number | undefined;
  let tooltipContentProps: ComponentProps<typeof TooltipContent> | undefined;
  if (tooltip) {
    if (typeof tooltip === "string") {
      tooltipContentProps = { children: tooltip };
    } else {
      const { delay, ...rest } = tooltip;
      tooltipOpenDelay = delay;
      tooltipContentProps = rest;
    }
  }

  // With `render` (e.g. Next.js `Link`), `useRender` merges `className` onto the outer
  // `TooltipTrigger`, not the custom element — clone so variants + `.selected` hit the real control.
  const resolvedRender = isValidElement(render)
    ? cloneElement(render, {
        className: cn(
          menuButtonClassName,
          (render.props as { className?: string }).className
        ),
      } as Attributes)
    : render;

  const comp = useRender({
    defaultTagName: "button",
    props: mergeProps<"button">(
      isValidElement(render)
        ? {}
        : {
            className: menuButtonClassName,
          },
      props
    ),
    render: tooltip ? (
      <TooltipTrigger delay={tooltipOpenDelay} render={resolvedRender} />
    ) : (
      resolvedRender
    ),
    state: {
      slot: "sidebar-menu-button",
      sidebar: "menu-button",
      size,
      active: isActive,
    },
  });

  if (!(tooltip && tooltipContentProps)) {
    return comp;
  }

  const tooltipElement = (
    <Tooltip>
      {comp}
      <TooltipContent
        align="center"
        hidden={state !== "collapsed" || isMobile}
        side="right"
        {...tooltipContentProps}
      />
    </Tooltip>
  );

  // Wrap in a provider so this tooltip's delay wins over any ancestor
  // `TooltipProvider` group delay (Base UI's group logic otherwise clamps
  // per-trigger delay to 0 when the group provider delay is 0).
  if (tooltipOpenDelay !== undefined) {
    return (
      <TooltipProvider delay={tooltipOpenDelay}>
        {tooltipElement}
      </TooltipProvider>
    );
  }

  return tooltipElement;
}

